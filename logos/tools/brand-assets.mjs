// Builds the site's brand files from logos/export (the eye isotype).
// Run: node logos/eye/gen.mjs && node logos/tools/export-eye.mjs && node logos/tools/brand-assets.mjs
// The animated GIF/MP4 files come from: node logos/anim/gen.mjs (ONLY=look renders just the brand motion).
import fs from "node:fs";
import { execFileSync } from "node:child_process";
import { motionCss } from "./eye-motion.mjs";

const ex = "logos/export";
const INK = "#111216", WHITE = "#FFFFFF";
const logo = fs.readFileSync(`${ex}/logo.svg`, "utf8");
const icon = fs.readFileSync(`${ex}/icon.svg`, "utf8");
const iconBody = icon.match(/<g id="icon">[\s\S]*<\/g>(?=<\/svg>)/)[0];

// Drawing box of the isotype inside its 512 box, measured by export-eye.mjs.
const BOX = JSON.parse(fs.readFileSync(`${ex}/icon-box.json`, "utf8"));
// Colour roles: ring (bone, thick), ring (grey, thin), pupil (red). Each ground has its own set.
const DARK = { ring: "#F1EDE4", ring2: "#B9B4A8", pupil: "#FF5A4A" };
const SETS = {
  color: DARK,
  light: { ring: INK, ring2: "#77736A", pupil: "#E8402F" },
  white: { ring: WHITE, ring2: WHITE, pupil: WHITE },
  black: { ring: INK, ring2: INK, pupil: INK },
};
const badge = (set = DARK) => {
  let g = iconBody;
  for (const role of Object.keys(DARK)) g = g.replaceAll(`"${DARK[role]}"`, `"@${role}"`);
  for (const role of Object.keys(DARK)) g = g.replaceAll(`"@${role}"`, `"${set[role]}"`);
  return g;
};

// App icon: square tile (no rounding, platforms apply their own mask). The eye is round, so it is centred on its
// own centre (256, 256) and sized so the ring's outer edge spans `fill` of the tile: safe under circle masks too.
const RING_D = 2 * 183;
const tile = (size, { bg = INK, set = DARK, fill = 0.56 } = {}) => {
  const s = (size * fill) / RING_D, t = size / 2 - 256 * s;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}"><rect width="${size}" height="${size}" fill="${bg}"/>` +
    `<g transform="translate(${t.toFixed(2)} ${t.toFixed(2)}) scale(${s.toFixed(4)})">${badge(set)}</g></svg>\n`;
};
const isoBox = `${(BOX.x - 4).toFixed(2)} ${(BOX.y - 4).toFixed(2)} ${(BOX.w + 8).toFixed(2)} ${(BOX.h + 8).toFixed(2)}`;
const isotype = (set = DARK, extra = "") => `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${isoBox}">${extra}${badge(set)}</svg>\n`;

// Variants for the isotype and the app icon.
const ISOTYPES = { color: SETS.color, light: SETS.light, white: SETS.white, black: SETS.black };
const APPICONS = {
  color: { bg: INK, set: SETS.color },
  light: { bg: WHITE, set: SETS.light },
  white: { bg: INK, set: SETS.white },
  black: { bg: WHITE, set: SETS.black },
};

// Site logo: the wordmark follows currentColor so header/footer can theme it; the eye keeps its colours.
fs.mkdirSync("src/assets/brand", { recursive: true });
fs.writeFileSync("src/assets/brand/logo-horizontal.svg", logo.replace(/(<g id="wordmark"[^>]*><path fill=")#F1EDE4/, "$1currentColor"));
fs.writeFileSync("src/assets/brand/isotype.svg", isotype());
// The site's motion: the same look-and-blink, with a longer rest so it stays calm in the header.
fs.writeFileSync("src/styles/brand-motion.css", `/* Generated by logos/tools/brand-assets.mjs from logos/tools/eye-motion.mjs. */\n` +
  motionCss({ period: 9, scope: ".ns-eye" }));

// Public brand kit
fs.rmSync("public/brand", { recursive: true, force: true });
fs.mkdirSync("public/brand", { recursive: true });
for (const f of ["logo.svg", "logo-light.svg", "logo-mono-ink.svg", "logo-mono-bone.svg"]) fs.copyFileSync(`${ex}/${f}`, `public/brand/neostation-${f}`);
for (const [k, set] of Object.entries(ISOTYPES)) fs.writeFileSync(`public/brand/neostation-isotype-${k}.svg`, isotype(set));
for (const [k, opts] of Object.entries(APPICONS)) fs.writeFileSync(`public/brand/neostation-appicon-${k}.svg`, tile(512, opts));
// Animated isotype (SVG + CSS), for the web: looks up-right, down-left, and blinks.
const style = `<style>${motionCss()}</style>`;
fs.writeFileSync("public/brand/neostation-isotype-animated.svg", isotype(SETS.color, style));
fs.writeFileSync("public/brand/neostation-isotype-animated-light.svg", isotype(SETS.light, style));
// GIF and MP4 renders of the same motion.
fs.mkdirSync("public/brand/motion", { recursive: true });
for (const g of ["dark", "light"]) for (const ext of ["gif", "mp4"]) fs.copyFileSync(`logos/anim/a4x-look-${g}.${ext}`, `public/brand/motion/neostation-isotype-${g}.${ext}`);

// Favicons and touch icon
fs.writeFileSync("public/favicon.svg", tile(64));
const raster = (svg, size, out) => { fs.writeFileSync("/tmp/ns-tile.svg", svg); execFileSync("rsvg-convert", ["-w", String(size), "-h", String(size), "/tmp/ns-tile.svg", "-o", out]); };
raster(tile(512), 512, "public/favicon.png");
fs.mkdirSync("public/icons", { recursive: true });
raster(tile(180), 180, "public/icons/apple-touch-icon.png");
console.log("brand assets written");

// Downloadable brand kit: SVGs, PNGs, motion and a short usage sheet, zipped into public/brand/.
const kit = "/tmp/neostation-brand-kit";
fs.rmSync(kit, { recursive: true, force: true });
for (const d of ["svg", "png", "motion"]) fs.mkdirSync(`${kit}/${d}`, { recursive: true });
for (const f of fs.readdirSync("public/brand").filter((f) => f.endsWith(".svg"))) fs.copyFileSync(`public/brand/${f}`, `${kit}/svg/${f}`);
for (const f of fs.readdirSync("public/brand/motion")) fs.copyFileSync(`public/brand/motion/${f}`, `${kit}/motion/${f}`);
// PNGs are named after their SVG plus the width, and published both in the kit and in public/brand/png/.
const PNG_SIZES = { logo: [600, 1200, 2400], isotype: [256, 512, 1024], appicon: [256, 512, 1024] };
fs.mkdirSync("public/brand/png", { recursive: true });
const png = (svgName, w, square) => {
  const out = `${svgName.replace(/\.svg$/, "")}-${w}.png`;
  execFileSync("rsvg-convert", ["-w", String(w), ...(square ? ["-h", String(w)] : []), `public/brand/${svgName}`, "-o", `public/brand/png/${out}`]);
  fs.copyFileSync(`public/brand/png/${out}`, `${kit}/png/${out}`);
};
for (const f of ["neostation-logo.svg", "neostation-logo-light.svg", "neostation-logo-mono-ink.svg", "neostation-logo-mono-bone.svg"]) for (const w of PNG_SIZES.logo) png(f, w);
for (const k of Object.keys(ISOTYPES)) for (const w of PNG_SIZES.isotype) png(`neostation-isotype-${k}.svg`, w);
for (const k of Object.keys(APPICONS)) for (const w of PNG_SIZES.appicon) png(`neostation-appicon-${k}.svg`, w, true);
fs.writeFileSync(`${kit}/README.txt`, `NeoStation brand kit

The mark
- An eye: a ring in two weights (bone and grey) with a red pupil. NeoStation watches over a whole retro
  library and shows it on every screen. The ring's two gaps sit on one diagonal; the eye looks and blinks
  along that same diagonal.

Logo
- neostation-logo.svg: for dark backgrounds (bone wordmark).
- neostation-logo-light.svg: for light backgrounds (ink wordmark, deeper red and grey).
- neostation-logo-mono-*.svg: one-colour versions for print or embroidery.
- neostation-isotype-{color,light,white,black}.svg: the eye alone (color = on dark, light = on light).
- neostation-appicon-{color,light,white,black}.svg: the eye on a square tile (platforms apply their own corner mask).
- Keep clear space around the logo equal to the height of the wordmark's capital N.
- Do not recolour, rotate, stretch or outline the eye, and do not swap the two ring weights.

Motion
- neostation-isotype-animated.svg / -animated-light.svg: the eye looks up-right, down-left, and blinks (4 s loop,
  SVG + CSS, stops when the viewer asks for reduced motion).
- motion/neostation-isotype-{dark,light}.{gif,mp4}: the same motion as GIF and MP4.
- Use the motion for loading, splash and social posts; keep the logo still in body text and print.

Colours
- Ink           #111216  background
- Bone          #F1EDE4  ring (thick) and wordmark on dark
- Grey          #B9B4A8  ring (thin) on dark
- Signal red    #FF5A4A  the pupil; the website's main action colour
- On light: ink #111216, grey #77736A, red #E8402F
Text on red or bone is ink (#111216).

Type
- Wordmark: Bai Jamjuree Bold Italic (SIL Open Font License).
- Interface and text: Bai Jamjuree; labels and data: JetBrains Mono.

The NeoStation name and logo identify the NeoStation project. Use them to refer to NeoStation,
not to suggest endorsement of other products.
`);
fs.rmSync("public/brand/neostation-brand-kit.zip", { force: true });
execFileSync("zip", ["-qr", `${process.cwd()}/public/brand/neostation-brand-kit.zip`, "."], { cwd: kit });
console.log("brand kit zipped");
